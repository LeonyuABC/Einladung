export function quoteForIdentity(quote, identity) {
    const person = identity === "Daria" ? "Daria" : "Yaoyu";
    return {
        ...quote,
        zh: typeof quote.zh === "object" ? quote.zh[person] : quote.zh,
        uk: typeof quote.uk === "object" ? quote.uk[person] : quote.uk
    };
}

export function dailyQuoteStartIndex(date = new Date()) {
    const key = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
    let hash = 0;
    for (const char of key) hash = ((hash << 5) - hash + char.charCodeAt(0)) | 0;
    return Math.abs(hash) % LOVE_QUOTES.length;
}
